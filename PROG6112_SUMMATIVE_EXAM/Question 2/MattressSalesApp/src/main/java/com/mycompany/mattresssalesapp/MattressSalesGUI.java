    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
String customer = txtCustomerName.getText();
String product = null;
        

try {
    double price = Double.parseDouble(txtPrice.getText());

    double vat = price * 0.15;
    double commission = price * 0.05;
    double total = price + vat + commission;

    String report = "Customer: " + customer
            + "\nProduct: " + product
            + "\nPrice: R" + price
            + "\nVAT: R" + vat
            + "\nCommission: R" + commission
            + "\nTotal: R" + total;

    JOptionPane.showMessageDialog(this, report);

    try (java.io.PrintWriter writer =
            new java.io.PrintWriter(
            new java.io.FileWriter("data.txt", true))) {
        writer.println(report);
        writer.println("--------------------");
    }

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this, "Enter a valid price.");
} catch (java.io.IOException e) {
    JOptionPane.showMessageDialog(this, "Error saving file.");
}        // TODO add your handling code here:
    }//GEN-LAST:event_jButton1ActionPerformed

